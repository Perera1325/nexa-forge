import type { NexaEdge, NexaNode, NodeRuntime } from '../types';

/** Everything the engine needs to know about a workflow. Plain data, no UI types beyond the shared model. */
export interface WorkflowGraph {
  nodes: NexaNode[];
  edges: NexaEdge[];
}

// ---------------------------------------------------------------- errors

export type ExecutionErrorCode =
  | 'unknown-kind' // a block whose type this version does not know
  | 'invalid-edge' // connection with a missing endpoint, or into a block without an input / out of one without an output
  | 'duplicate-edge' // the same connection twice
  | 'self-loop' // a block connected to itself
  | 'cycle' // blocks that feed each other, so no valid order exists
  | 'invalid-config' // a setting the block cannot run with
  | 'unreachable' // not connected to any sensor, so it never receives data
  | 'no-sensor' // nothing generates data
  | 'node-failed'; // a block threw while executing

/** A problem found while planning or running. Errors stop the affected block; warnings only inform. */
export interface ExecutionError {
  code: ExecutionErrorCode;
  level: 'error' | 'warning';
  message: string;
  nodeId?: string;
  edgeId?: string;
}

// ---------------------------------------------------------------- node status

/**
 * idle     – no data reached the block in this step
 * ok       – the block processed data
 * blocked  – a Logic block evaluated its condition as false
 * prepared – a Docker / Kubernetes block received data; it only prepares configuration (simulated)
 * skipped  – the block cannot run (disconnected, in a cycle, unknown type)
 * failed   – invalid configuration or an execution failure
 */
export type NodeStatus = 'idle' | 'ok' | 'blocked' | 'prepared' | 'skipped' | 'failed';

export interface NodeState {
  status: NodeStatus;
  /** Last value the block handled. */
  value?: number;
  /** For Logic blocks: the result of the last evaluation. */
  passed?: boolean;
  /** How many steps the block has processed data in this run. */
  runs: number;
  /** Why the block failed or was skipped. */
  reason?: string;
}

// ---------------------------------------------------------------- events

export type EventLevel = 'debug' | 'info' | 'event' | 'warn' | 'error';

export type ExecutionEventKind =
  | 'run.started'
  | 'run.notice'
  | 'run.stopped'
  | 'issue'
  | 'sensor.reading'
  | 'logic.evaluated'
  | 'mqtt.publish'
  | 'api.request'
  | 'docker.prepare'
  | 'kubernetes.prepare';

export interface ExecutionEvent {
  kind: ExecutionEventKind;
  level: EventLevel;
  /** Block name, or "Simulation" / "Workflow" for run-level events. */
  source: string;
  message: string;
  tick: number;
  nodeId?: string;
  /** Structured details for tests and tools. `simulated` is always present on events that stand for external actions. */
  data?: Record<string, string | number | boolean>;
}

// ---------------------------------------------------------------- results

/** A reading travelling along the connections. */
export interface Signal {
  sensorId: string;
  value: number;
  unit: string;
}

export interface TickOutput {
  tick: number;
  events: ExecutionEvent[];
  /** Reading generated by each sensor in this step. */
  readings: Record<string, number>;
  /** Cumulative per-block status for the current run. */
  nodes: Record<string, NodeState>;
  /** Which blocks handled data in this step (used to highlight them on the canvas). */
  runtime: Record<string, NodeRuntime>;
}

export interface StartOutput {
  events: ExecutionEvent[];
  nodes: Record<string, NodeState>;
}

export interface StopOutput {
  events: ExecutionEvent[];
  nodes: Record<string, NodeState>;
}
